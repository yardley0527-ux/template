    def topics(question, answer = nil)
      tags(TOPICS, question, answer, TOPICS.except(*HEALTH_TOPICS))
    end

    def tags(rules, question, answer, answer_rules = rules)
      found = match(rules, question)
      found.empty? ? match(answer_rules, answer) : found
    end

